"""
============================================================
System Prompt 模板（Agent 的"总指令"）
============================================================

【教学说明】什么是 System Prompt？
System Prompt 是你给 AI 的一段"角色设定"。它不是商家说的话，
而是你（开发者）提前告诉 AI 的"行为准则"。

类比 Java：就像你在 Spring Boot 的 @PreAuthorize 里写权限规则一样，
System Prompt 就是给 AI 写的"行为规则"。

DeepSeek 每次收到商家的消息时，都会先看这段 System Prompt，
然后再决定怎么回复。所以 System Prompt 写得好不好，
直接决定了 Agent 的表现好不好。

【教学说明】Prompt 的"三板斧"写法：
1. 角色定义 —— 你是谁？
2. 能力边界 —— 你能做什么？不能做什么？
3. 输出格式 —— 你回复的时候应该遵循什么格式？

这是 v1 版本（最简版），后续我们会根据测试结果不断迭代。
"""

